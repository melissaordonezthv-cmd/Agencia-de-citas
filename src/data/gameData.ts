export function getFilteredCharacters(pref: DatePreference): CharacterProfile[] {
  if (pref === "chicas") return CHARACTERS.filter((c) => c.gender === "chica");
  if (pref === "chicos") return CHARACTERS.filter((c) => c.gender === "chico");
  return CHARACTERS;
}

export function rollTimedDate(char: CharacterProfile, isInitialGreeting = false): boolean {
  if (isInitialGreeting) {
    // Only very busy dificil jobs occasionally start timed on greeting (~12%), easy/medium almost never
    const base = char.difficulty === "dificil" ? (char.busyProbability ?? 0.25) * 0.45 : 0;
    return Math.random() < base;
  }
  return Math.random() < (char.busyProbability ?? 0.12);
}

