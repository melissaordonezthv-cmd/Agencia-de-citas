export function calculateAttractiveness(appearance: ChibiAppearance): number {
  const outfit =
    WARDROBE_ITEMS.find((i) => i.category === "outfit" && i.value === appearance.outfit)
      ?.attractiveness || 0;
  const hair =
    WARDROBE_ITEMS.find((i) => i.category === "hair" && i.value === appearance.hairStyle)
      ?.attractiveness || 0;
  const acc =
    WARDROBE_ITEMS.find(
      (i) => i.category === "accessory" && i.value === appearance.accessory
    )?.attractiveness || 0;
  const eye =
    WARDROBE_ITEMS.find((i) => i.category === "eye" && i.value === appearance.eyeStyle)
      ?.attractiveness || 0;
  const mouth =
    WARDROBE_ITEMS.find(
      (i) => i.category === "mouth" && i.value === (appearance.mouthStyle || "smile_soft")
    )?.attractiveness || 0;
  const markBonus = appearance.faceMark && appearance.faceMark !== "ninguno" ? 2 : 0;
  return outfit + hair + acc + eye + mouth + markBonus;
}

